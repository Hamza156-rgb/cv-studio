// Copies the website's resume-document styles (all templates) into the mobile app, so the
// in-app preview is identical to the website preview and PDF. Runs before dev and build.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = dirname(fileURLToPath(import.meta.url));
const webStyles = ["index.css", "styles/polish.css", "styles/depth.css"].map((file) => resolve(here, "../../client/src", file));
const output = resolve(here, "../src/generated/resume.css");
const sharedResume = readFileSync(resolve(here, "../../shared/resume.ts"), "utf8");
const TEMPLATE_IDS = new Set([...sharedResume.matchAll(/\{ id: "([a-z]+)"/g)].map((match) => match[1]));

// Only classes the resume component itself renders count as "document" classes, so site UI that
// shares the "resume-" prefix (dashboard cards, the editor zoom) is left out.
const component = readFileSync(resolve(here, "../../client/src/components/resume/ResumeDocument.tsx"), "utf8");
const documentClasses = new Set(component.match(/resume-[a-z0-9-]+/g));
const isDocumentClass = (name) => documentClasses.has(name)
  || /^resume-(scale|section)-[a-z]+$/.test(name) // built as `resume-scale-${...}` / `resume-section-${...}`
  || /^resume-[a-z]+$/.test(name) && TEMPLATE_IDS.has(name.slice(7))
  || /^font-(modern|serif|classic)$/.test(name) || /^photo-(circle|rounded|square)$/.test(name);

/** A selector belongs to the document when its leading compound selector only uses document classes. */
function isDocumentSelector(selector) {
  const leading = selector.trim().split(/\s*[>+~]\s*|\s+/)[0];
  if (/^(html|body|:root|\*)/.test(leading)) return false;
  const classes = [...leading.matchAll(/\.([a-zA-Z0-9_-]+)/g)].map((match) => match[1]);
  return classes.length > 0 && classes.every(isDocumentClass);
}

let fontImport = "";
const kept = [];
for (const file of webStyles) {
  const root = postcss.parse(readFileSync(file, "utf8"), { from: file });
  root.walkAtRules("import", (rule) => { if (!fontImport && rule.params.includes("fonts.googleapis.com")) fontImport = rule.toString(); });
  root.each((node) => {
    if (node.type === "rule" && node.selectors.every(isDocumentSelector)) kept.push(node.toString());
    if (node.type === "atrule" && node.name === "media" && !/print/.test(node.params)) {
      const inner = [];
      node.walkRules((rule) => { if (rule.selectors.every(isDocumentSelector)) inner.push(rule.toString()); });
      if (inner.length) kept.push(`@media ${node.params} {\n${inner.join("\n")}\n}`);
    }
  });
}

// The website gets these defaults from Tailwind's preflight; :where() keeps them zero-specificity.
const reset = `:where(.resume-document, .resume-document *, .resume-document *::before, .resume-document *::after) { box-sizing: border-box; border: 0 solid; margin: 0; padding: 0; }
:where(.resume-document) :where(h1, h2, h3, h4) { font-size: inherit; font-weight: inherit; }
:where(.resume-document) :where(ul, ol) { list-style: none; }
:where(.resume-document) :where(img) { display: block; max-width: 100%; }
:where(.resume-document) :where(a) { color: inherit; text-decoration: inherit; }`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `/* GENERATED by scripts/extract-resume-css.mjs from client/src — do not edit. */\n${fontImport}\n${reset}\n${kept.join("\n")}\n`);
console.log(`resume.css: ${kept.length} rules from the website stylesheets`);
